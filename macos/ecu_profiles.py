"""Профили электронных блоков (ЭБУ) автомобилей.

Разные блоки машины (двигатель, коробка, ABS, подушки, кузов) сидят
на разных CAN-адресах. Стандартный OBD-II видит только двигатель,
поэтому для чтения кодов из остальных блоков нужно обращаться по адресу.

ВАЖНО: адреса зависят от марки, модели и года выпуска. Здесь собраны
типовые адреса, которые чаще всего работают. Если блок не ответил —
это нормально: значит, у вашей машины он на другом адресе.

Поэтому приложение умеет два режима:
  1. По профилю марки — пробует известные адреса.
  2. Автопоиск — перебирает стандартный диапазон 7E0–7E7.
"""

