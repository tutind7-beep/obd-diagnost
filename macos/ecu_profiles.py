def profile_for(make: str) -> list[dict]:
    """Возвращает профиль блоков для марки (или типовой)."""
    if not make:
        return list(DEFAULT_PROFILE)
    for brand, profile in BRAND_PROFILES.items():
        if brand.lower() == make.strip().lower():
            return list(profile)
    return list(DEFAULT_PROFILE)


def list_brands() -> list[str]:
    """Список марок, для которых есть профиль."""
    return sorted(BRAND_PROFILES.keys())
