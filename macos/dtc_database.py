def lookup_dtc(code: str) -> tuple[str, str] | None:
    """Ищет код в базе. Возвращает (название, пояснение) или None."""
    return DTC_DATABASE.get(code.strip().upper())


def total_codes() -> int:
    """Сколько кодов в базе."""
    return len(DTC_DATABASE)
